class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to compute total page numbers ("Page X of Y")
    and render professional headers and footers on every page after the cover.
    """

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_header_footer(num_pages)
            super().showPage()
        super().save()

    def draw_header_footer(self, page_count: int):
        # Skip header and footer on Cover Page (Page 1)
        if self._pageNumber == 1:
            return

        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))

        # Header (Top margin: 0.75 in = 54 pt, Letter height = 11 in = 792 pt)
        header_text = "CONFIDENTIAL — COMPLYAI ENTERPRISE AUDIT REPORT"
        self.drawString(54, 792 - 36, header_text)
        self.setStrokeColor(colors.HexColor("#CBD5E1"))
        self.setLineWidth(0.5)
        self.line(54, 792 - 42, 612 - 54, 792 - 42)

        # Footer
        self.line(54, 48, 612 - 54, 48)
        page_str = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(612 - 54, 34, page_str)
        self.drawString(54, 34, "Generated by ComplyAI Engine • Legal & Compliance Copilot")
        self.restoreState()


